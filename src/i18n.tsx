type Ctx = { lang: Lang; setLang: (l: Lang) => void }
const LangCtx = createContext<Ctx>({ lang: 'ru', setLang: () => {} })

const missing = new Set<string>()
;(window as unknown as { __i18nMissing: Set<string> }).__i18nMissing = missing

function initialLang(): Lang {
  const q = new URLSearchParams(window.location.search).get('lang')
  if (q === 'kz' || q === 'ru') return q
  try { return localStorage.getItem('lang') === 'kz' ? 'kz' : 'ru' } catch { return 'ru' }
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  useEffect(() => { document.documentElement.lang = lang === 'kz' ? 'kk' : 'ru' }, [lang])
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem('lang', l) } catch { /* без памяти */ } }
  return <LangCtx.Provider value={{ lang, setLang }}>{children}</LangCtx.Provider>
}

export const useLang = () => useContext(LangCtx)

/** t('русский текст') → текст на текущем языке */
export function useT() {
  const { lang } = useContext(LangCtx)
  return (s: string) => {
    if (lang === 'ru' || !s) return s
    const v = KZ[s]
    if (v === undefined) missing.add(s)
    return v ?? s
  }
}

export function LangSwitch({ className = '' }: { className?: string }) {
  const { lang, setLang } = useLang()
  const t = useT()
  return (
    <div role="group" aria-label={t('Язык')} className={`inline-flex rounded-full border border-white/25 p-1 text-xs font-bold ${className}`}>
      {(['ru', 'kz'] as const).map((l) => (
        <button
          key={l}
          type="button"
          aria-pressed={lang === l}
          onClick={() => setLang(l)}
          className={`px-2.5 sm:px-3 py-1.5 rounded-full transition-colors ${lang === l ? 'bg-mint text-ink' : 'text-sage hover:text-white'}`}
        >
          {l === 'ru' ? 'РУС' : 'ҚАЗ'}
        </button>
      ))}
    </div>
  )
}
